async(page)=>{
 const check=(ok,message)=>{if(!ok)throw Error(message)};
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5202/');
 await page.getByRole('button',{name:'Explore demo',exact:false}).click();
 const nav=name=>page.getByRole('navigation',{name:'Main navigation',exact:true}).getByRole('button',{name,exact:true});
 await nav('Money').click();
 await page.getByRole('button',{name:'Money entry',exact:true}).click();
 await page.locator('input[name=amount]').fill('12.50');
 await page.locator('input[name=note]').fill('Reward QA entry');
 await page.getByRole('button',{name:'Save entry',exact:true}).click();
 await page.locator('.toast img[src="/companions/logging.webp"]').waitFor();
 check((await page.locator('.toast').innerText()).includes('Demo'),'Demo status absent');
 await page.screenshot({path:'output/reward-logging-desktop.png'});
 await page.getByRole('button',{name:'Dismiss notification'}).click();
 await page.getByRole('button',{name:'Edit Reward QA entry',exact:true}).click();
 await page.getByRole('button',{name:'Save entry',exact:true}).click();
 check(await page.locator('.toast img').count()===0,'Editing should not award art');
 await page.getByRole('button',{name:'Dismiss notification'}).click();
 await page.getByRole('button',{name:'Add to goal',exact:false}).first().click();
 await page.locator('input[name=amount]').fill('5');
 await page.getByRole('button',{name:'Save contribution'}).click();
 await page.locator('.toast img[src="/companions/savings.webp"]').waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'output/reward-savings-mobile.png'});
 const box=await page.locator('.toast').boundingBox();check(box.x>=0&&box.x+box.width<=390,'Mobile toast overflows');
 const bottom=await page.getByRole('navigation',{name:'Mobile navigation'}).boundingBox();check(box.y+box.height<=bottom.y,'Toast covers navigation');
 await page.getByRole('button',{name:'Dismiss notification'}).click();
 await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('button',{name:'Movement',exact:true}).click();
 await page.getByRole('button',{name:'Log a workout'}).click();
 await page.getByRole('button',{name:'Save workout',exact:true}).click();
 await page.locator('.toast img[src="/companions/workout.webp"]').waitFor();
 await page.emulateMedia({reducedMotion:'reduce'});
 check(await page.locator('.toast .sticker').evaluate(el=>getComputedStyle(el).animationName)==='none','Reduced motion not respected');
 await page.screenshot({path:'output/reward-workout-mobile.png'});
 check(await page.locator('.toast img').evaluate(img=>img.complete&&img.naturalWidth>0),'Broken reward image');
 await page.getByRole('button',{name:'Dismiss notification'}).click();
 await page.getByRole('button',{name:'History',exact:true}).click();
 await page.getByRole('button',{name:'View workout recap'}).first().click();
 await page.locator('[role=dialog] img[src="/companions/workout.webp"]').waitFor();
 check((await page.locator('.recap-save-status').innerText()).includes('Demo'),'Recap save status missing');
 await page.getByRole('button',{name:'Done for now'}).click();
 check(errors.length===0,errors.join('\n'));
 return {passed:['new money reward','edit is text only','savings reward','390px placement','dismissal','manual workout','reduced motion','loaded art','recap with save status'],errors};
}
